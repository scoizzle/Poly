using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;

using Poly.DomainModeling.Compile;
using Poly.DomainModeling.Ontology;
using Poly.Tests.TestHelpers;

namespace Poly.Tests.DomainModeling.Compile;

/// <summary>
/// E-03 (#685, ruling Q13 / #659): each domain's emitted types live in a namespace named after the
/// domain, carried by <see cref="CompilationUnitNode.Namespace"/>. The type-list overload
/// <c>Write(typeDefs)</c> stays the global legacy path (plan lock A1).
/// </summary>
public sealed class CSharpNamespaceTests {
    private const string Shop = """
        domain Shop
        Item: entity {
          Name: Text
          Open: stage { Close: action { transition to Done } }
          Done: stage { }
        }
        Order: entity {
          Number: Number
        }
        """;

    private const string Tracker = """
        domain Tracker
        Item: entity {
          Label: Text
          Open: stage { Close: action { transition to Done } }
          Done: stage { }
        }
        """;

    [Test]
    public async Task CSharpNamespace_DerivesFromDomainName() {
        var (domain, _, _) = SliceCProducerLoopCatalogTests.Evolve(Shop);

        await Assert.That(DomainSession.CSharpNamespace(domain)).IsEqualTo("Shop");
    }

    [Test]
    [Arguments("class", "keyword")]
    [Arguments("Poly", "Poly")]
    [Arguments("System", "System")]
    [Arguments("a..b", "a..b")]
    [Arguments("Poly.Shop", "Poly")]
    [Arguments("Café", "Café")]
    [Arguments("1Shop", "1Shop")]
    public async Task CSharpNamespace_NonIdentifierKeywordOrReservedName_FailsClosed(string name, string expectedInMessage) {
        var (domain, _, _) = SliceCProducerLoopCatalogTests.Evolve(Shop);

        var thrown = Assert.Throws<InvalidOperationException>(
            () => DomainSession.CSharpNamespace(domain with { Name = name }));

        await Assert.That(thrown!.Message).Contains(expectedInMessage);
        await Assert.That(thrown.Message).Contains("E-10");
    }

    [Test]
    public async Task Emit_RefusedNamespace_LeavesNoCatalogOnTheSession() {
        var (domain, analysis, session) = SliceCProducerLoopCatalogTests.Evolve(Shop);

        Assert.Throws<InvalidOperationException>(() => session.Emit(domain with { Name = "class" }, analysis));

        await Assert.That(session.ArtifactCatalog.Artifacts.Count).IsEqualTo(0);
    }

    [Test]
    public async Task EveryEmittedFile_IsInDomainNamespace_AndCompilesTogether() {
        var (domain, analysis, session) = SliceCProducerLoopCatalogTests.Evolve(Shop);

        var files = session.Emit(domain, analysis);

        foreach (var (name, source) in files.Where(f => f.FileName != "Poly.Types.cs" || f.Source != "#nullable enable"))
            await Assert.That(source).Contains("namespace Shop;").Because(name);
        var asm = ExportedCSharp.CompileAndLoad(files, "ShopNamespace");
        await Assert.That(asm.GetType("Shop.Item")).IsNotNull();
        await Assert.That(asm.GetType("Shop.Order")).IsNotNull();
        await Assert.That(asm.GetType("Item")).IsNull();
    }

    [Test]
    public async Task EveryEmittedTypeIsInsideTheDomainNamespace() {
        var (domain, analysis, session) = SliceCProducerLoopCatalogTests.Evolve(Shop);

        var files = session.Emit(domain, analysis);

        var checkedFiles = 0;
        foreach (var (name, source) in files) {
            var root = CSharpSyntaxTree.ParseText(source).GetCompilationUnitRoot();
            var global = root.Members.Where(m => m is BaseTypeDeclarationSyntax or DelegateDeclarationSyntax).ToList();
            await Assert.That(global.Count).IsEqualTo(0).Because($"{name} declares a global type");
            var ns = root.Members.OfType<FileScopedNamespaceDeclarationSyntax>().SingleOrDefault();
            if (ns is null)
                continue;
            checkedFiles++;
            await Assert.That(ns.Name.ToString()).IsEqualTo(DomainSession.CSharpNamespace(domain)).Because(name);
        }
        await Assert.That(checkedFiles).IsGreaterThan(0);
    }

    [Test]
    public async Task Emit_Output_BeginsWithBannerAndNullable_ExceptTheEmptyScaffoldingFile() {
        var (domain, analysis, session) = SliceCProducerLoopCatalogTests.Evolve(Shop);

        var files = session.Emit(domain, analysis);

        foreach (var (name, source) in files) {
            if (name == "Poly.Types.cs" && source == "#nullable enable")
                continue;
            await Assert.That(source.StartsWith("// <auto-generated/>\n\n#nullable enable\n", StringComparison.Ordinal))
                .IsTrue().Because($"{name}: {source}");
        }
    }

    [Test]
    public async Task TwoDomains_OneAssembly_NoCollision() {
        var (shop, shopAnalysis, shopSession) = SliceCProducerLoopCatalogTests.Evolve(Shop);
        var (tracker, trackerAnalysis, trackerSession) = SliceCProducerLoopCatalogTests.Evolve(Tracker);
        var files = shopSession.Emit(shop, shopAnalysis)
            .Select(f => ("Shop." + f.FileName, f.Source))
            .Concat(trackerSession.Emit(tracker, trackerAnalysis).Select(f => ("Tracker." + f.FileName, f.Source)))
            .ToList();

        var asm = ExportedCSharp.CompileAndLoad(files, "TwoDomains");

        await Assert.That(asm.GetType("Shop.Item")).IsNotNull();
        await Assert.That(asm.GetType("Tracker.Item")).IsNotNull();
        await Assert.That(asm.GetType("Shop.ItemStage")).IsNotNull();
        await Assert.That(asm.GetType("Tracker.ItemStage")).IsNotNull();
    }
}