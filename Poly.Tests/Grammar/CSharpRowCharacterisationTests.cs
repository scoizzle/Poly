using Poly.Interpretation;
using Poly.Interpretation.CSharp;
using Poly.Introspection;

namespace Poly.Tests.Grammar;

/// <summary>
/// G-23b step 0: what the C# writer prints today for the shapes the slice moves, pinned green on master
/// before any production edit. Each pin that a later commit changes is rewritten by that commit; the
/// change is one of the named byte moves in the pull-request body.
/// </summary>
public class CSharpRowCharacterisationTests {
    private const string UnitHeader = "// <auto-generated/>\n\n#nullable enable\n\n";

    private static string Lf(string text) => text.ReplaceLineEndings("\n");

    private static CompilationUnitNode Unit(params Node[] statements) => new([], null, [], statements);

    private static string UnitBody(CompilationUnitNode unit) {
        var text = Lf(CSharpLanguage.Write(unit));
        return text.StartsWith(UnitHeader, StringComparison.Ordinal) ? text[UnitHeader.Length..] : text;
    }

    private static CompilationUnitNode MethodBody(string body) =>
        CSharpLanguage.Read($"class C {{ void M() {{ {body} }} }}");

    [Test]
    public async Task NestedUndeclaredAssignment_PrintsAPlainAssignmentInsideTheExpression() {
        var x = new Variable("x");
        var y = new Variable("y");
        var text = UnitBody(Unit(new Assignment(x, new Assignment(y, new Constant(1L)))));
        await Assert.That(text).IsEqualTo("var x = y = 1L;");
        await Assert.That(CSharpLanguage.Read(text).TopLevelStatements).IsNotNull();
    }

    [Test]
    public async Task TopLevelUndeclaredForInitializer_PrintsAnAssignment() {
        var x = new Variable("x");
        var loop = new ForLoop(new Assignment(x, new Constant(0L)), new LessThan(x, new Constant(10L)),
            new Assignment(x, new Add(x, new Constant(1L))), new Block(new Constant(0L)));
        await Assert.That(UnitBody(Unit(loop)))
            .IsEqualTo("for (x = 0L; x < 10L; x = x + 1L)\n{\n    _ = 0L;\n}");
    }

    [Test]
    public async Task UndeclaredTopLevelAssignment_PrintsAFusedVarStatement() {
        await Assert.That(UnitBody(Unit(new Assignment(new Variable("x"), new Constant(1L))))).IsEqualTo("var x = 1L;");
        await Assert.That(UnitBody(CSharpLanguage.Read("var x = 1L;"))).IsEqualTo("var x = 1L;");
    }

    [Test]
    public async Task BlockLambdas_PrintTheirBlockIntoTheExpressionSlot() {
        await Assert.That(UnitBody(CSharpLanguage.Read("Func<long, long> f = x => { return x; };")))
            .IsEqualTo("var f = (Func<long, long>)(x => {\n    return x;\n});");
        await Assert.That(UnitBody(CSharpLanguage.Read("Func<long, long> f = (long x) => { return x; };")))
            .IsEqualTo("var f = (Func<long, long>)((long x) => {\n    return x;\n});");
        await Assert.That(UnitBody(CSharpLanguage.Read("Func<Task, Task> f = async x => { await x; };")))
            .IsEqualTo("var f = (Func<Task, Task>)(async x => {\n    await x;\n});");
    }

    [Test]
    public async Task EmptyEnum_PrintsEmptyBraces() {
        await Assert.That(Lf(CSharpLanguage.Write([new TypeDefinitionNode("Empty", Kind: TypeKind.Enum)])))
            .IsEqualTo("#nullable enable\npublic enum Empty\n{}");
        await Assert.That(Lf(CSharpLanguage.Write([new TypeDefinitionNode("Empty", Fields: [], Kind: TypeKind.Enum)])))
            .IsEqualTo("#nullable enable\npublic enum Empty\n{}");
    }

    [Test]
    public async Task EnumValues_PrintTheirDeclaredValue() {
        await Assert.That(UnitBody(CSharpLanguage.Read("enum E { A = 5, B = 7 }")))
            .IsEqualTo("public enum E\n{\n    A = 5,\n    B = 7\n}");
    }

    [Test]
    public async Task DeclaredEnumMember_IsNotResolvableOnTheVmToday() {
        var result = CSharpScript.Run("enum E { A = 5 } E.A;");
        await Assert.That(result.Success).IsFalse();
        await Assert.That(string.Join(";", result.Diagnostics)).Contains("Variable 'E' is not declared in this scope");
    }

    [Test]
    public async Task Interface_PrintsBracesAndEveryMemberWithItsAccess() {
        await Assert.That(UnitBody(CSharpLanguage.Read("interface IShape { int Sides { get; } long Area(long scale); }")))
            .IsEqualTo("public interface IShape\n{\n    public int Sides { get; }\n    public long Area(long scale);\n}");
        await Assert.That(Lf(CSharpLanguage.Write([new TypeDefinitionNode("I", Kind: TypeKind.Interface,
                Properties: [new PropertyDefinitionNode("P", TypeReference.To<int>())])])))
            .IsEqualTo("#nullable enable\npublic interface I\n{\n    public System.Int32 P { get; set; }\n}");
    }

    [Test]
    public async Task Label_PrintsItsLabelThenItsStatement() {
        await Assert.That(Lf(CSharpLanguage.Write(new LabelDeclaration("exit", new Return(new Constant(0L))))))
            .IsEqualTo("exit:\nreturn 0L;");
    }

    private const string ShadowedParameterCallee = """var s = "hi"; var n = ((long s) => s + 1)(4); n;""";
    private const string NestedShadowedParameterCallee =
        """var s = 1000; var n = ((long s) => ((long s) => s + 1)(5) + s)(10); n;""";

    [Test]
    [Arguments(ShadowedParameterCallee)]
    [Arguments(NestedShadowedParameterCallee)]
    public async Task ShadowedParameterCallee_RefusedWithoutAnalysis_PrintsWithIt(string body) {
        var unit = MethodBody(body);
        await Assert.That(() => CSharpLanguage.Write(unit)).Throws<InvalidOperationException>()
            .WithMessageContaining("a lambda used as a callee needs a delegate type to cast to");
        var analysed = new CSharpWriter(Interpreter.Analyze(unit)).Write(unit);
        await Assert.That(analysed).Contains("((System.Func<long, long>)((long s_2) =>");
    }

    [Test]
    public async Task ShadowedParameterCallee_AnalysedText_ReReadsToTheSameText() {
        var unit = MethodBody(ShadowedParameterCallee);
        var analysed = new CSharpWriter(Interpreter.Analyze(unit)).Write(unit);
        await Assert.That(CSharpLanguage.Write(CSharpLanguage.Read(analysed))).IsEqualTo(analysed);
    }
}