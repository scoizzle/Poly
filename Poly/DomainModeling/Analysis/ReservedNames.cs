using Poly.DomainModeling.Meaning;
using Poly.DomainModeling.Ontology;

namespace Poly.DomainModeling.Analysis;

/// <summary>The generated surface a reserved name lands on.</summary>
internal enum ReservedKind {
    /// <summary>C# itself: a member cannot carry its enclosing type's name (CS0542).</summary>
    Language,

    /// <summary>A property, field, or method on the generated entity class.</summary>
    GeneratedMember,

    /// <summary>A top-level type the module emits next to the entity classes.</summary>
    GeneratedType,

    /// <summary>A namespace the generated C# imports.</summary>
    Namespace,
}

/// <summary>
/// One name the C# exporter generates, and the reason it is unavailable to the author.
/// <paramref name="AppliesTo"/> restricts a fixed row to the entities the emitter actually
/// generates it on; null means every entity.
/// </summary>
internal sealed record ReservedName(
    string Name,
    ReservedKind Kind,
    string Reason,
    Func<Entity, bool>? AppliesTo = null);

/// <summary>
/// The single table of names the generated C# surface reserves (S-01, #528 #519). Every row
/// is cited from the emitter that writes it; a name the emitter can generate but this table
/// does not list is a defect, which <c>NameScopeTests.EmitterParity_EntityMembers_AreReservedOrGap</c>
/// pins.
///
/// C# keywords are deliberately absent (OQ-12b, E-10 owns escaping): <c>class</c> and
/// <c>event</c> are authorable and legal.
///
/// Subscription-derived names (handler <c>When…</c>, <c>Notify{Stage}Subscribers</c>,
/// <c>Register…Subscriber</c>, the registry field, <c>InitializeSubscriptions</c>, and the
/// notify cascade depth guard) are a named gap owned by S-05/L-14. <c>IsReservedExpressionWord</c>
/// on <see cref="StructuralDomainAnalyzer"/> stays a second, expression-only list (G-06/G-21).
/// </summary>
internal static class ReservedNames {
    private static readonly ReservedName[] Fixed = [
        // Create.cs:558 — every entity publishes the static Create factory.
        new("Create", ReservedKind.GeneratedMember, "the create factory"),
        // Stages.cs:105 — only an entity that declares stages.
        new("CurrentStage", ReservedKind.GeneratedMember, "the current-stage property",
            static entity => entity.Stages.Count > 0),
        // Invariants.cs:43 — only an entity with a `unique` property.
        new("EnsureUnique", ReservedKind.GeneratedMember, "the unique-assign invariant",
            HasUniqueProperty),
        // Stages.cs:49,83 with condition Stages.cs:39 — automatic transitions.
        new("NoteAutomaticStage", ReservedKind.GeneratedMember, "the automatic-transition guard",
            EffectHelpers.HasAutomaticTransitions),
        new("ClearAutomaticStageChain", ReservedKind.GeneratedMember, "the automatic-transition guard",
            EffectHelpers.HasAutomaticTransitions),
        // Stages.cs:41 — the chain field the guard nulls.
        new("_automaticStageChain", ReservedKind.GeneratedMember, "the automatic-transition chain field",
            EffectHelpers.HasAutomaticTransitions),
        // DomainToCSharpExporter.cs:257,369 — the module scaffolding types.
        new("DomainResult", ReservedKind.GeneratedType,
            "collides with the scaffolding type generated by Emit"),
        new("ConstraintFailureException", ReservedKind.GeneratedType,
            "collides with the scaffolding type generated by Emit"),
        // CSharpWriter.cs:99-100 — `using System;` when UseSystem.
        new("System", ReservedKind.Namespace,
            "shadows the System namespace the generated C# imports"),
    ];

    /// <summary>Every fixed row, unfiltered by entity.</summary>
    public static IReadOnlyList<ReservedName> All => Fixed;

    /// <summary>
    /// The rows that apply to <paramref name="entity"/>: the fixed rows its shape triggers,
    /// its own name, its stage enum, and the per-navigation members and factories.
    /// Reconciliation source for the emitter-parity test.
    /// </summary>
    public static IReadOnlyList<ReservedName> ForEntity(Entity entity) =>
        [.. Rows(entity, includeNavigationMembers: true)];

    /// <summary>
    /// True when <paramref name="identity"/> is reserved on <paramref name="owner"/>. A
    /// navigation's own generated property is not listed here: it is the member itself, not
    /// a name it can collide with.
    /// </summary>
    public static bool TryReserved(string identity, Entity owner, out ReservedName row) {
        foreach (var candidate in Rows(owner, includeNavigationMembers: false)) {
            if (!string.Equals(candidate.Name, identity, StringComparison.Ordinal))
                continue;
            row = candidate;
            return true;
        }
        row = null!;
        return false;
    }

    private static bool HasUniqueProperty(Entity entity) =>
        entity.Properties.Any(static prop => prop.Constraints.OfType<UniqueConstraint>().Any());

    private static IEnumerable<ReservedName> Rows(Entity entity, bool includeNavigationMembers) {
        foreach (var row in Fixed) {
            if (row.AppliesTo is null || row.AppliesTo(entity))
                yield return row;
        }

        // #528: CS0542 — a member cannot be named like its enclosing type.
        yield return new ReservedName(entity.Name, ReservedKind.Language, "the enclosing type's name");

        // Stages.cs:16,102 with EntityStructureMetadata.cs:30.
        if (entity.Stages.Count > 0)
            yield return new ReservedName(
                $"{entity.Name}Stage", ReservedKind.GeneratedType, "the stage enum generated for this entity");

        foreach (var nav in entity.Navigations) {
            // Relationships.cs:143,164,184.
            var pascalName = DomainTypeMapping.ToPascalCase(nav.Name);
            // Create.cs:61; the factory exists only for a nav something creates in (Relationships.cs:173,182).
            if (EffectHelpers.CreatesIn(entity, nav.Name))
                yield return new ReservedName($"Create{pascalName}", ReservedKind.GeneratedMember, "the create-in factory");
            // Relationships.cs:39 — collection navs only.
            if (nav.Cardinality is RelationshipCardinality.OneToMany or RelationshipCardinality.ManyToMany)
                yield return new ReservedName($"Attach{pascalName}", ReservedKind.GeneratedMember, "the attach method");
            if (!includeNavigationMembers)
                continue;
            yield return new ReservedName(pascalName, ReservedKind.GeneratedMember, "the navigation property");
            // Relationships.cs:149.
            if (nav.Cardinality is RelationshipCardinality.OneToMany or RelationshipCardinality.ManyToMany) {
                yield return new ReservedName(
                    $"_{DomainTypeMapping.ToCamelCase(pascalName)}", ReservedKind.GeneratedMember,
                    "the navigation collection field");
            }
        }
    }
}