using System.Net;
using System.Text;

using Poly.DomainModeling.Analysis;
using Poly.DomainModeling.Ontology;

using Entity = Poly.DomainModeling.Ontology.Entity;
using EnumType = Poly.DomainModeling.Ontology.EnumType;
using ValueType = Poly.DomainModeling.Ontology.ValueType;

namespace Poly.DomainModeling.Queries;

/// <summary>
/// A self-contained HTML document for a person: one file, no scripts, no server. It is a
/// reading view over the same facts the Markdown report and the RDF/JSON exports use, so
/// a human can open the ontology in a browser and an agent can hand them the file. Types and
/// members appear in declaration order (Q12).
/// </summary>
public static class DomainHtmlExporter {
    public static string Export(Domain domain) {
        ArgumentNullException.ThrowIfNull(domain);
        return Export(new DomainExportContext(domain));
    }

    public static string Export(DomainExportContext context) {
        ArgumentNullException.ThrowIfNull(context);
        ArgumentNullException.ThrowIfNull(context.Domain);
        var domain = context.Domain;
        var printer = new Lazy<DomainDslPrinter>(context.CreatePrinter);

        var ordered = DomainExportOrder.Types(domain);
        var entities = ordered.OfType<Entity>().ToList();
        var valueTypes = ordered.OfType<ValueType>().ToList();
        var enums = ordered.OfType<EnumType>().ToList();
        var properties = entities.Sum(e => e.Properties.Count) + valueTypes.Sum(v => v.Properties.Count);
        var relationships = entities.Sum(e => e.Navigations.Count);

        var sb = new StringBuilder();
        sb.AppendLine("<!doctype html>");
        sb.AppendLine("<html lang=\"en\">");
        sb.AppendLine("<head>");
        sb.AppendLine("<meta charset=\"utf-8\">");
        sb.AppendLine("<meta name=\"viewport\" content=\"width=device-width, initial-scale=1\">");
        sb.AppendLine($"<title>{E(domain.Name)} — Poly ontology</title>");
        sb.AppendLine("<style>");
        sb.AppendLine(Css);
        sb.AppendLine("</style>");
        sb.AppendLine("</head>");
        sb.AppendLine("<body>");
        sb.AppendLine("<header>");
        sb.AppendLine("<p class=\"eyebrow\">Poly ontology</p>");
        sb.AppendLine($"<h1>{E(domain.Name)}</h1>");
        sb.AppendLine($"<p class=\"counts\">{E(Counts(entities.Count, enums.Count, valueTypes.Count, relationships, properties))}</p>");
        sb.AppendLine("</header>");

        var sections = entities.Select(e => $"<a href=\"#entity-{E(e.Name)}\">{E(e.Name)}</a>")
            .Concat(enums.Select(e => $"<a href=\"#enum-{E(e.Name)}\">{E(e.Name)}</a>"))
            .Concat(valueTypes.Select(v => $"<a href=\"#value-{E(v.Name)}\">{E(v.Name)}</a>"))
            .ToList();
        if (sections.Count > 0) {
            sb.AppendLine("<nav>");
            sb.AppendLine(string.Join(" · ", sections));
            if (relationships > 0)
                sb.AppendLine(" · <a href=\"#relationships\">Relationships</a>");
            sb.AppendLine("</nav>");
        }

        sb.AppendLine("<main>");
        foreach (var entity in entities)
            AppendEntity(sb, entity, printer);
        foreach (var enumType in enums)
            AppendEnum(sb, enumType);
        foreach (var valueType in valueTypes)
            AppendValueType(sb, valueType);
        if (relationships > 0)
            AppendRelationships(sb, entities);
        sb.AppendLine("</main>");

        sb.AppendLine("<footer>Generated by Poly from the domain facts.</footer>");
        sb.AppendLine("</body>");
        sb.AppendLine("</html>");
        return sb.ToString();
    }

    private static void AppendEntity(StringBuilder sb, Entity entity, Lazy<DomainDslPrinter> printer) {
        sb.AppendLine($"<section id=\"entity-{E(entity.Name)}\">");
        sb.AppendLine($"<h2>{E(entity.Name)}</h2>");
        AppendTerm(sb, entity.Facets);

        if (entity.Properties.Count > 0) {
            sb.AppendLine("<table>");
            sb.AppendLine("<thead><tr><th>Property</th><th>Type</th><th>Constraints</th><th>Required</th><th>IRI</th></tr></thead>");
            sb.AppendLine("<tbody>");
            var entryAssigned = EntityStructureAnalyzer.ComputeEntryAssignedPropertyNames(entity);
            foreach (var property in EntityDeclarationOrder.Properties(entity)) {
                var term = TermFacets.Read(property.Facets);
                var required = DomainPresentation.IsRequired(property, entryAssigned);
                sb.AppendLine("<tr>");
                sb.AppendLine($"<td>{E(property.Name)}</td>");
                sb.AppendLine($"<td>{E(property.Type.TypeName)}</td>");
                sb.AppendLine($"<td>{ConstraintCell(property)}</td>");
                sb.AppendLine($"<td>{(required ? "<span class=\"req\">required</span>" : "<span class=\"opt\">optional</span>")}</td>");
                sb.AppendLine($"<td>{IriCell(term)}</td>");
                sb.AppendLine("</tr>");
            }
            sb.AppendLine("</tbody>");
            sb.AppendLine("</table>");
        }

        if (entity.Stages.Count > 0) {
            sb.AppendLine("<h3>Stages</h3>");
            sb.AppendLine("<table><thead><tr><th>Stage</th><th>Actions</th></tr></thead><tbody>");
            foreach (var stage in entity.Stages) {
                var stageActionNames = stage.Actions.Count == 0
                    ? "—"
                    : string.Join(", ", stage.Actions.Select(a => a.Name));
                sb.AppendLine($"<tr><td>{E(stage.Name)}</td><td>{E(stageActionNames)}</td></tr>");
            }
            sb.AppendLine("</tbody></table>");
        }

        var actions = entity.Actions
            .Select(a => (Stage: (string?)null, Action: a))
            .Concat(entity.Stages.SelectMany(s => s.Actions.Select(a => (Stage: (string?)s.Name, Action: a))))
            .ToList();
        if (actions.Count > 0) {
            sb.AppendLine("<h3>Actions</h3>");
            sb.AppendLine("<table><thead><tr><th>Action</th><th>Stage</th><th>Parameters</th><th>Guards</th></tr></thead><tbody>");
            foreach (var (stage, action) in actions) {
                var parameters = action.Parameters.Count == 0
                    ? "—"
                    : string.Join(", ", action.Parameters.Select(p => $"{p.Name}: {p.Type.TypeName}"));
                var guards = action.Policies.Count == 0
                    ? "—"
                    : string.Join(", ", action.Policies.Select(p => p.Name));
                sb.AppendLine($"<tr><td>{E(action.Name)}</td><td>{E(stage ?? "entity")}</td>" +
                    $"<td>{E(parameters)}</td><td>{E(guards)}</td></tr>");
            }
            sb.AppendLine("</tbody></table>");
        }

        var policies = PolicyProjection.For(entity, printer);
        if (policies.Count > 0) {
            sb.AppendLine("<h3>Policies</h3>");
            sb.AppendLine("<table><thead><tr><th>Policy</th><th>Scope</th><th>Condition</th></tr></thead><tbody>");
            foreach (var policy in policies) {
                sb.AppendLine($"<tr><td>{E(policy.Name)}</td><td>{E(policy.Scope)}</td>" +
                    $"<td><code>{E(policy.ConditionText)}</code></td></tr>");
            }
            sb.AppendLine("</tbody></table>");
        }

        sb.AppendLine("</section>");
    }

    private static void AppendEnum(StringBuilder sb, EnumType enumType) {
        sb.AppendLine($"<section id=\"enum-{E(enumType.Name)}\">");
        sb.AppendLine($"<h2>{E(enumType.Name)} <span class=\"kind\">enum</span></h2>");
        AppendTerm(sb, enumType.Facets);
        sb.AppendLine("<table><thead><tr><th>Member</th><th>IRI</th><th>Term</th></tr></thead><tbody>");
        foreach (var member in enumType.MemberNames) {
            var term = TermFacets.Read(enumType.MemberFacets.GetValueOrDefault(member));
            sb.AppendLine($"<tr><td>{E(member)}</td><td>{IriCell(term)}</td>" +
                $"<td>{(term?.Term is { } name ? $"<code>{E(name)}</code>" : "—")}</td></tr>");
        }
        sb.AppendLine("</tbody></table>");
        sb.AppendLine("</section>");
    }

    private static void AppendValueType(StringBuilder sb, ValueType valueType) {
        sb.AppendLine($"<section id=\"value-{E(valueType.Name)}\">");
        sb.AppendLine($"<h2>{E(valueType.Name)} <span class=\"kind\">value type</span></h2>");
        AppendTerm(sb, valueType.Facets);
        if (valueType.Properties.Count == 0) {
            sb.AppendLine("</section>");
            return;
        }

        sb.AppendLine("<table><thead><tr><th>Property</th><th>Type</th><th>Constraints</th><th>Required</th><th>IRI</th></tr></thead><tbody>");
        var entryAssigned = new HashSet<string>(StringComparer.Ordinal);
        foreach (var property in valueType.Properties) {
            var term = TermFacets.Read(property.Facets);
            var required = DomainPresentation.IsRequired(property, entryAssigned);
            sb.AppendLine($"<tr><td>{E(property.Name)}</td><td>{E(property.Type.TypeName)}</td>" +
                $"<td>{ConstraintCell(property)}</td>" +
                $"<td>{(required ? "<span class=\"req\">required</span>" : "<span class=\"opt\">optional</span>")}</td>" +
                $"<td>{IriCell(term)}</td></tr>");
        }
        sb.AppendLine("</tbody></table>");
        sb.AppendLine("</section>");
    }

    private static void AppendRelationships(StringBuilder sb, IReadOnlyList<Entity> entities) {
        sb.AppendLine("<section id=\"relationships\">");
        sb.AppendLine("<h2>Relationships</h2>");
        sb.AppendLine("<table><thead><tr><th>Source</th><th>Name</th><th>Target</th><th>Cardinality</th></tr></thead><tbody>");
        foreach (var (source, navigation) in entities
            .SelectMany(e => EntityDeclarationOrder.Navigations(e).Select(n => (Source: e, Navigation: n)))) {
            sb.AppendLine($"<tr><td>{E(source.Name)}</td><td>{E(navigation.Name)}</td>" +
                $"<td>{E(navigation.Target.TypeName)}</td>" +
                $"<td>{E(DomainPresentation.Cardinality(navigation.Cardinality))}</td></tr>");
        }
        sb.AppendLine("</tbody></table>");
        sb.AppendLine("</section>");
    }

    private static void AppendTerm(StringBuilder sb, IReadOnlyList<Facet> facets) {
        var term = TermFacets.Read(facets);
        if (term is null)
            return;
        if (term.Iri is { } iri)
            sb.AppendLine($"<p class=\"iri\"><code>{E(iri)}</code></p>");
        if (term.Description is { } description)
            sb.AppendLine($"<p class=\"description\">{E(description)}</p>");
    }

    private static string ConstraintCell(Property property) {
        var constraints = DomainPresentation.Constraints(property);
        return constraints is null ? "—" : $"<code>{E(constraints)}</code>";
    }

    private static string IriCell(TermMetadata? term) =>
        term?.Iri is { } iri ? $"<code>{E(iri)}</code>" : "—";

    private static string Counts(int entities, int enums, int valueTypes, int relationships, int properties) =>
        string.Join(" · ",
            Count(entities, "entity", "entities"),
            Count(enums, "enum", "enums"),
            Count(valueTypes, "value type", "value types"),
            Count(relationships, "relationship", "relationships"),
            Count(properties, "property", "properties"));

    private static string Count(int count, string singular, string plural) =>
        $"{count} {(count == 1 ? singular : plural)}";

    /// <summary>HTML-escape every model-authored string; descriptions are untrusted input.</summary>
    private static string E(string text) => WebUtility.HtmlEncode(text);

